/**
 * dsh-locale-ko-extra — Korean strings for the DeepSeek Harness web UI.
 *
 * Works two ways:
 *   1. Standalone (dsh-locale-ko disabled): registers the `ko` language and every
 *      namespace dictionary itself, from the snapshot in base/ko.json.
 *   2. Overlay (dsh-locale-ko enabled): the pack already owns these namespaces, and
 *      the locale runtime rejects a second registration for the same namespace and
 *      language, so this plugin merges its extra entries straight into the
 *      dictionary objects the runtime holds (locale.dicts), which every lookup reads.
 *
 * The first install is deferred by one turn so a real language pack activating in the
 * same boot pass always gets to register `ko` first; this plugin then only merges.
 *
 * Generated by tools/build-client.cjs from base/ko.json + overrides/ko.overrides.json.
 */
{
const CORE = /*__CORE__*/ {};
const PLUGIN = /*__PLUGIN__*/ {};

const note = (level, message) => {
  try { console[level]('[dsh-locale-ko-extra] ' + message) } catch {}
};

/** Merge entries into a live dictionary; returns an undo function when anything changed. */
const mergeInto = (dict, entries) => {
  const undo = [];
  for (const key of Object.keys(entries)) {
    const value = entries[key];
    const had = Object.prototype.hasOwnProperty.call(dict, key);
    const previous = dict[key];
    if (previous === value) continue;
    dict[key] = value;
    undo.push(() => { if (had) dict[key] = previous; else delete dict[key] });
  }
  return undo.length
    ? () => { for (const step of undo) { try { step() } catch {} } }
    : null;
};

/** The dictionary the runtime holds for one namespace in Korean, if any. */
const korean = (dicts, namespace) => {
  const byLanguage = dicts.get(namespace);
  return byLanguage && typeof byLanguage.get === 'function' ? byLanguage.get('ko') : undefined;
};

window.__ModuleLoader__.load({
  id: 'dsh-locale-ko-extra',
  factory: () => ({
    inject: ['locale'],
    apply(ctx) {
      const locale = ctx.locale;
      const dicts = locale.dicts;
      if (!dicts || typeof dicts.get !== 'function') {
        note('warn', 'this locale runtime exposes no dictionary table; translations were not applied');
        return;
      }

      let repainting = false;
      const repaint = () => {
        if (repainting) return;
        repainting = true;
        queueMicrotask(() => {
          repainting = false;
          try { locale.publish(locale.snapshot.active, false) } catch {}
        });
      };

      let applied = 0;
      let merging = false;
      let started = false;
      const undoStack = [];

      const ensureLanguage = () => {
        try {
          const snapshot = locale.getSnapshot ? locale.getSnapshot() : locale.snapshot;
          const locales = (snapshot && snapshot.locales) || [];
          if (locales.some((item) => item.id === 'ko')) return;
          ctx.effect(
            () => locale.addLanguage({ id: 'ko', label: '한국어', fallback: 'en' }),
            'dsh-locale-ko-extra: language',
          );
        } catch (error) {
          note('warn', 'could not register the ko language: ' + error.message);
        }
      };

      /** Own the namespace when it is free, otherwise merge into the existing dictionary. */
      const install = (namespace, entries) => {
        const owned = korean(dicts, namespace);
        if (owned) {
          const undo = mergeInto(owned, entries);
          applied++;
          if (undo) undoStack.push(undo);
          return;
        }
        try {
          undoStack.push(locale.register(namespace, 'ko', entries));
          applied++;
        } catch (error) {
          const now = korean(dicts, namespace);
          if (!now) {
            note('warn', 'could not install "' + namespace + '": ' + error.message);
            return;
          }
          const undo = mergeInto(now, entries);
          applied++;
          if (undo) undoStack.push(undo);
        }
      };

      // Third-party namespaces are only claimed once their owner registered something
      // (dsh-locale-ko defers these the same way). Re-checked on every locale change.
      const pending = Object.keys(PLUGIN);
      const attach = () => {
        for (let index = pending.length - 1; index >= 0; index--) {
          const namespace = pending[index];
          if (!dicts.has(namespace)) continue;
          pending.splice(index, 1);
          install(namespace, PLUGIN[namespace]);
        }
      };

      const mergeAll = () => {
        for (const namespace of Object.keys(CORE)) {
          const dict = korean(dicts, namespace);
          if (!dict) continue;
          const undo = mergeInto(dict, CORE[namespace]);
          if (undo) { applied++; undoStack.push(undo); }
        }
        attach();
      };

      // Subscribe before installing: anything registered during boot must be seen even
      // if it happens before the deferred install below runs.
      ctx.effect(() => locale.subscribe(() => {
        if (merging) return;
        merging = true;
        try { mergeAll() } catch (error) { note('warn', 'merge failed: ' + error.message) } finally { merging = false }
      }), 'dsh-locale-ko-extra: dictionaries');

      const start = () => {
        if (started) return;
        started = true;
        try {
          ensureLanguage();
          for (const namespace of Object.keys(CORE)) install(namespace, CORE[namespace]);
          attach();
          if (applied) repaint();
        } catch (error) {
          note('warn', 'install failed: ' + error.message);
        }
      };

      const timer = setTimeout(start, 0);
      ctx.effect(() => () => { try { clearTimeout(timer) } catch {} }, 'dsh-locale-ko-extra: start');

      ctx.effect(() => () => {
        for (const undo of undoStack.splice(0)) { try { undo() } catch {} }
      }, 'dsh-locale-ko-extra: cleanup');
    },
  }),
})
}
